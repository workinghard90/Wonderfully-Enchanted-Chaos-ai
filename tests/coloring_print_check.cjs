/* Print-planning boundaries; no network or AI calls. */
const assert = require('node:assert/strict'), fs = require('node:fs'), path = require('node:path');
(async () => {
  const source = fs.readFileSync(path.join(__dirname, '../wec_engine/studio_web/coloring/print-check.js'));
  const {checkBook, fittedArtwork} = await import('data:text/javascript;base64,' + source.toString('base64'));
  const art = {name: 'original.png', width: 2250, height: 3000};
  const book = (count, backs = false) => checkBook(Array.from({length: count}, () => art), backs, 'Boundary proof');
  assert.equal(book(0).basic_checks_pass, false);
  assert.equal(book(11, true).checks[0].passes, false);
  const ready = book(12, true);
  assert.equal(ready.exported_pages, 24);
  assert.equal(ready.basic_checks_pass, true);
  assert.equal(ready.pdf_file_inspected, false);
  assert.equal(ready.publishing_review_required, true);
  assert.equal(ready.pages[11].pdf_page, 23);
  assert.equal(ready.pages[0].effective_ppi, 300);
  assert.deepEqual(ready.pages[0].pixels_at_target, [2250, 3000]);
  const odd = book(23);
  assert.equal(odd.kdp_rounded_pages, 24);
  assert.equal(odd.checks[0].passes, true);
  assert.match(odd.notices[0], /odd page count/);
  assert.equal(book(150).required_inside_margin_inches, .375);
  assert.equal(book(151).required_inside_margin_inches, .5);
  assert.equal(book(300).checks[1].passes, true);
  assert.equal(book(301).checks[1].passes, false);
  assert.equal(book(590).checks[0].passes, true);
  assert.equal(book(591).checks[0].passes, false);
  const landscape = fittedArtwork(3000, 1000);
  assert.equal(landscape.effective_ppi, 400);
  assert.equal(landscape.width_inches, 7.5);
  assert.equal(landscape.height_inches, 2.5);
  const sample = checkBook([{name: 'Pip.png', width: 1102, height: 1427}], true);
  assert.equal(Math.floor(sample.pages[0].effective_ppi), 146);
  assert.equal(sample.checks[2].passes, false);
  assert.equal(fittedArtwork(2249, 2999).meets_target, false);
  assert.throws(() => fittedArtwork(0, 2));
  assert.throws(() => fittedArtwork(NaN, 2));
  assert.throws(() => fittedArtwork(2.5, 2));
  console.log('PASS print planning: aspect ratio/PPI, page minimum/maximum/even rounding, gutter transitions, blank-back numbering, no PDF certification');
})().catch(error => {console.error(error); process.exit(1);});
